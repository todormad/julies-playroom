// The voiceover generator (tools/voice-prep/build-voice.mjs) reads every line from here.
export { STR as STRINGS };

export function loadLocale() {
  try {
    const saved = localStorage.getItem(KEY) || localStorage.getItem('astroBuddy_locale_v1');
    if (LOCALES.includes(saved)) locale = saved;
  } catch {}
  document.documentElement.lang = locale;
  return locale;
}

export function setLocale(next) {
  if (!LOCALES.includes(next)) return;
  locale = next;
  try { localStorage.setItem(KEY, next); } catch {}
  document.documentElement.lang = next;
}

export function getLocale() { return locale; }

export function has(key) { return key in STR[locale]; }

export function t(key, ...args) {
  const v = STR[locale][key] ?? STR.en[key] ?? key;
  return typeof v === 'function' ? v(...args) : v;
}

export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute('aria-label', el.title);
  });
}
